-- Creacion de la base
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run VARCHAR(12) NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    apellidos VARCHAR(150) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    contrasena VARCHAR(255) NOT NULL,
    telefono VARCHAR(25) NOT NULL,
    fecha_nacimiento DATE,
    region VARCHAR(150) NOT NULL,
    comuna VARCHAR(150) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    tipo_usuario VARCHAR(20) DEFAULT 'CLIENTE' NOT NULL,
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT uq_usuario_run UNIQUE (run),
    CONSTRAINT uq_usuario_correo UNIQUE (correo),
    CONSTRAINT ck_usuario_rol CHECK (tipo_usuario IN ('ADMINISTRADOR', 'VENDEDOR', 'CLIENTE'))
);

CREATE TABLE IF NOT EXISTS categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(1000),
    CONSTRAINT uq_categoria_nombre UNIQUE (nombre)
);

CREATE TABLE IF NOT EXISTS producto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL,
    nombre VARCHAR(200) NOT NULL,
    descripcion VARCHAR(2000),
    genero VARCHAR(30) NOT NULL,
    tipo VARCHAR(60) NOT NULL,
    precio DECIMAL(19, 2) NOT NULL,
    stock INTEGER DEFAULT 0 NOT NULL,
    stock_critico INTEGER DEFAULT 5 NOT NULL,
    tallas JSON NOT NULL,
    colores JSON NOT NULL,
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    CONSTRAINT fk_producto_categoria FOREIGN KEY (categoria_id) REFERENCES categoria(id),
    CONSTRAINT uq_producto_genero_tipo UNIQUE (genero, tipo),
    CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    CONSTRAINT ck_producto_stock CHECK (stock >= 0),
    CONSTRAINT ck_producto_stock_critico CHECK (stock_critico >= 0)
);

CREATE TABLE IF NOT EXISTS boleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero VARCHAR(40) NOT NULL,
    usuario_id BIGINT,
    fecha TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL,
    estado VARCHAR(20) DEFAULT 'PENDIENTE' NOT NULL,
    stock_reservado BOOLEAN DEFAULT FALSE NOT NULL,
    cliente_run VARCHAR(12) NOT NULL,
    cliente_nombre VARCHAR(100) NOT NULL,
    cliente_apellidos VARCHAR(150) NOT NULL,
    cliente_correo VARCHAR(254) NOT NULL,
    cliente_telefono VARCHAR(25) NOT NULL,
    entrega_region VARCHAR(150) NOT NULL,
    entrega_comuna VARCHAR(150) NOT NULL,
    entrega_calle VARCHAR(255) NOT NULL,
    entrega_departamento VARCHAR(100),
    entrega_indicaciones VARCHAR(1000),
    subtotal_neto DECIMAL(19, 2) NOT NULL,
    tasa_iva DECIMAL(5, 4) DEFAULT 0.1900 NOT NULL,
    monto_iva DECIMAL(19, 2) NOT NULL,
    costo_envio DECIMAL(19, 2) DEFAULT 0 NOT NULL,
    total DECIMAL(19, 2) NOT NULL,
    CONSTRAINT uq_boleta_numero UNIQUE (numero),
    CONSTRAINT fk_boleta_usuario FOREIGN KEY (usuario_id) REFERENCES usuario(id),
    CONSTRAINT ck_boleta_estado CHECK (estado IN ('PENDIENTE', 'PAGADA', 'PAGO_FALLIDO')),
    CONSTRAINT ck_boleta_subtotal CHECK (subtotal_neto >= 0),
    CONSTRAINT ck_boleta_tasa CHECK (tasa_iva BETWEEN 0 AND 1),
    CONSTRAINT ck_boleta_iva CHECK (monto_iva >= 0),
    CONSTRAINT ck_boleta_envio CHECK (costo_envio = 0),
    CONSTRAINT ck_boleta_total CHECK (total >= 0 AND total = subtotal_neto + monto_iva + costo_envio)
);

CREATE TABLE IF NOT EXISTS detalle_boleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    boleta_id BIGINT NOT NULL,
    producto_id BIGINT NOT NULL,
    producto_nombre VARCHAR(200) NOT NULL,
    talla VARCHAR(30) NOT NULL,
    color VARCHAR(60) NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario_neto DECIMAL(19, 2) NOT NULL,
    subtotal_neto DECIMAL(19, 2) NOT NULL,
    CONSTRAINT fk_detalle_boleta FOREIGN KEY (boleta_id) REFERENCES boleta(id),
    CONSTRAINT fk_detalle_producto FOREIGN KEY (producto_id) REFERENCES producto(id),
    CONSTRAINT ck_detalle_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_detalle_precio CHECK (precio_unitario_neto >= 0),
    CONSTRAINT ck_detalle_subtotal CHECK (subtotal_neto = cantidad * precio_unitario_neto)
);

CREATE INDEX IF NOT EXISTS idx_producto_categoria ON producto(categoria_id);
CREATE INDEX IF NOT EXISTS idx_boleta_usuario ON boleta(usuario_id);
CREATE INDEX IF NOT EXISTS idx_boleta_fecha ON boleta(fecha);
CREATE INDEX IF NOT EXISTS idx_detalle_boleta ON detalle_boleta(boleta_id);
CREATE INDEX IF NOT EXISTS idx_detalle_producto ON detalle_boleta(producto_id);
